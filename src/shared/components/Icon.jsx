/**
 * Peta nama -> komponen lucide. Kuncinya nama Material lama (snake_case) dan nama
 * lucide (kebab-case). Nilai yang `undefined` (ekspor lucide hilang) digagalkan tes.
 */
export const ICON_MAP = {
  ...LUCIDE,
  ...Object.fromEntries(Object.entries(NAMA_LAMA).map(([lama, baru]) => [lama, LUCIDE[baru]])),
}

const sudahDiperingatkan = new Set()

function peringatkanSekali(name) {
  if (!import.meta.env?.DEV) return
  const kunci = String(name)
  if (sudahDiperingatkan.has(kunci)) return
  sudahDiperingatkan.add(kunci)
  console.warn(`[Icon] nama ikon "${kunci}" tidak ada di ICON_MAP; memakai ikon cadangan.`)
}

/**
 * Ikon lucide. Tanpa `label` ikon bersifat dekoratif (aria-hidden); dengan `label`
 * ikon menjadi gambar beraksesibilitas (role="img").
 */
export function Icon({ name, size = 18, strokeWidth = 1.75, className, label, ...rest }) {
  const Komponen = Object.hasOwn(ICON_MAP, name) ? ICON_MAP[name] : undefined
  if (!Komponen) peringatkanSekali(name)
  const Dipakai = Komponen || FALLBACK_ICON
  const aksesibilitas = label
    ? { role: 'img', 'aria-label': label }
    : { 'aria-hidden': 'true', focusable: 'false' }
  return <Dipakai size={size} strokeWidth={strokeWidth} className={className} {...aksesibilitas} {...rest} />
}
